/* Bird gallery: filterable species grid plus a map of where each was seen.
   Data comes from assets/birds/data.json, generated by build_site.py in the
   birds working folder from the photos' own embedded metadata. */

(function () {
  "use strict";

  var BASE = document.currentScript.src.replace(/\/app\.js.*$/, "");
  var S = {
    data: null,
    map: null,
    cluster: null,
    view: "gallery",
    visible: [], // species currently shown, in display order
    lb: { items: [], i: 0 },
  };

  function $(id) {
    return document.getElementById(id);
  }

  function url(kind, file) {
    return BASE + "/" + kind + "/" + encodeURIComponent(file);
  }

  /* ---------- filtering ---------- */

  function currentFilters() {
    return {
      q: $("birds-search").value.trim().toLowerCase(),
      family: $("birds-family").value,
      location: $("birds-location").value,
      sort: $("birds-sort").value,
    };
  }

  function matches(sp, f) {
    if (f.family && sp.family !== f.family) return false;
    if (
      f.location &&
      !sp.photos.some(function (p) {
        return p.location === f.location;
      })
    )
      return false;
    if (f.q) {
      var hay = (sp.en + " " + sp.zh + " " + sp.sciName + " " + sp.family + " " + sp.order).toLowerCase();
      if (hay.indexOf(f.q) === -1) return false;
    }
    return true;
  }

  function latestDate(sp) {
    return sp.photos.reduce(function (a, p) {
      return p.date > a ? p.date : a;
    }, "");
  }

  function apply() {
    var f = currentFilters();
    var list = S.data.species.filter(function (sp) {
      return matches(sp, f);
    });

    if (f.sort === "alpha") {
      list.sort(function (a, b) {
        return a.en.localeCompare(b.en);
      });
    } else if (f.sort === "recent") {
      list.sort(function (a, b) {
        return latestDate(b).localeCompare(latestDate(a));
      });
    } else {
      list.sort(function (a, b) {
        return a.taxonOrder - b.taxonOrder;
      });
    }

    S.visible = list;
    renderGrid(list, f);
    updateStats(list, f);
    if (S.view === "map") renderMarkers(list, f);
  }

  /* ---------- gallery ---------- */

  function renderGrid(list, f) {
    var grid = $("birds-grid");
    grid.innerHTML = "";
    $("birds-empty").hidden = list.length > 0;

    var frag = document.createDocumentFragment();
    list.forEach(function (sp, idx) {
      // Respect a location filter when choosing which photo represents the species.
      var pool = f.location
        ? sp.photos.filter(function (p) {
            return p.location === f.location;
          })
        : sp.photos;
      var photo = pool[pool.length - 1]; // highest number = most recent

      var card = document.createElement("div");
      card.className = "bird-card";
      card.tabIndex = 0;
      card.setAttribute("role", "button");
      card.setAttribute("aria-label", sp.en + " " + sp.zh);

      var thumb = document.createElement("div");
      thumb.className = "thumb";
      thumb.style.backgroundImage = 'url("' + url("thumbs", photo.file) + '")';

      var meta = document.createElement("div");
      meta.className = "meta";
      meta.innerHTML = '<div class="en"></div><div class="zh"></div>' + '<div class="sub"></div><div class="count"></div>';
      meta.querySelector(".en").textContent = sp.en;
      meta.querySelector(".zh").textContent = sp.zh;
      meta.querySelector(".sub").textContent = photo.date + " · " + (S.data.locations[photo.location] || {}).display;
      if (sp.photos.length > 1) {
        meta.querySelector(".count").textContent = sp.photos.length + " photos";
      }

      card.append(thumb, meta);
      card.addEventListener("click", function () {
        openLightbox(idx, f);
      });
      card.addEventListener("keydown", function (e) {
        if (e.key === "Enter" || e.key === " ") {
          e.preventDefault();
          openLightbox(idx, f);
        }
      });
      frag.appendChild(card);
    });
    grid.appendChild(frag);
  }

  function updateStats(list, f) {
    var photos = list.reduce(function (a, sp) {
      return (
        a +
        (f.location
          ? sp.photos.filter(function (p) {
              return p.location === f.location;
            }).length
          : sp.photos.length)
      );
    }, 0);
    var all = S.data.stats;
    var showing =
      list.length === all.species
        ? all.species + " species · " + all.photos + " photos · " + all.locations + " locations · " + all.families + " families"
        : list.length + " of " + all.species + " species · " + photos + " photos";
    $("birds-stats").textContent = showing;
  }

  /* ---------- lightbox ---------- */

  function openLightbox(speciesIdx, f) {
    var sp = S.visible[speciesIdx];
    var pool =
      f && f.location
        ? sp.photos.filter(function (p) {
            return p.location === f.location;
          })
        : sp.photos;
    S.lb.items = pool.map(function (p) {
      return { sp: sp, p: p };
    });
    S.lb.i = pool.length - 1;
    showLightbox();
  }

  function showLightbox() {
    var it = S.lb.items[S.lb.i];
    if (!it) return;
    var loc = S.data.locations[it.p.location] || {};
    $("birds-lightbox-img").src = url("web", it.p.file);
    $("birds-lightbox-img").alt = it.sp.en + " — " + (loc.display || "");
    $("birds-lightbox-meta").innerHTML = '<div class="lb-title"></div><div class="lb-sci"></div><div class="lb-where"></div>';
    var m = $("birds-lightbox-meta");
    m.querySelector(".lb-title").textContent = it.sp.en + " " + it.sp.zh;
    m.querySelector(".lb-sci").textContent = it.sp.sciName + " · " + it.sp.family;
    m.querySelector(".lb-where").textContent =
      it.p.date +
      " · " +
      (loc.display || "") +
      (loc.approximate ? " (approx.)" : "") +
      (S.lb.items.length > 1 ? "  —  " + (S.lb.i + 1) + " / " + S.lb.items.length : "");

    var box = $("birds-lightbox");
    box.classList.add("open");
    box.setAttribute("aria-hidden", "false");
    var multi = S.lb.items.length > 1;
    box.querySelector(".lb-prev").style.display = multi ? "" : "none";
    box.querySelector(".lb-next").style.display = multi ? "" : "none";
  }

  function closeLightbox() {
    var box = $("birds-lightbox");
    box.classList.remove("open");
    box.setAttribute("aria-hidden", "true");
    $("birds-lightbox-img").src = "";
  }

  function step(d) {
    if (!S.lb.items.length) return;
    S.lb.i = (S.lb.i + d + S.lb.items.length) % S.lb.items.length;
    showLightbox();
  }

  /* ---------- map ---------- */

  function markerIcon(count, approximate) {
    var size = Math.max(24, Math.min(52, 16 + Math.sqrt(count) * 7));
    return L.divIcon({
      html:
        '<div class="bird-marker' + (approximate ? " approximate" : "") + '" style="width:' + size + "px;height:" + size + 'px;">' + count + "</div>",
      className: "",
      iconSize: [size, size],
      iconAnchor: [size / 2, size / 2],
    });
  }

  function ensureMap() {
    if (S.map) return;
    S.map = L.map("birds-map", { worldCopyJump: true, scrollWheelZoom: false }).setView([25, -40], 2);
    L.tileLayer("https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png", {
      maxZoom: 18,
      attribution: '&copy; <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a>',
    }).addTo(S.map);
  }

  function renderMarkers(list, f) {
    ensureMap();
    if (S.cluster) S.map.removeLayer(S.cluster);
    S.cluster = L.markerClusterGroup({ showCoverageOnHover: false, maxClusterRadius: 45 });

    var byLoc = {};
    list.forEach(function (sp) {
      sp.photos.forEach(function (p) {
        if (f.location && p.location !== f.location) return;
        (byLoc[p.location] = byLoc[p.location] || new Set()).add(sp.en);
      });
    });

    var bounds = [];
    Object.keys(byLoc).forEach(function (key) {
      var loc = S.data.locations[key];
      if (!loc) return;
      var n = byLoc[key].size;
      var mk = L.marker([loc.lat, loc.lon], { icon: markerIcon(n, loc.approximate) });
      mk.bindTooltip(loc.display + " — " + n + " species" + (loc.approximate ? " (approx.)" : ""), { direction: "top", offset: [0, -10] });
      mk.on("click", function () {
        $("birds-location").value = key;
        setView("gallery");
        apply();
      });
      S.cluster.addLayer(mk);
      bounds.push([loc.lat, loc.lon]);
    });
    S.map.addLayer(S.cluster);
    if (bounds.length) S.map.fitBounds(bounds, { padding: [40, 40], maxZoom: 9 });
  }

  /* ---------- view switching ---------- */

  function setView(v) {
    S.view = v;
    $("birds-gallery").hidden = v !== "gallery";
    $("birds-map").hidden = v !== "map";
    $("birds-view-gallery").setAttribute("aria-pressed", String(v === "gallery"));
    $("birds-view-map").setAttribute("aria-pressed", String(v === "map"));
    if (v === "map") {
      renderMarkers(S.visible, currentFilters());
      setTimeout(function () {
        S.map.invalidateSize();
      }, 0);
    }
  }

  /* ---------- init ---------- */

  function fillSelects() {
    var fams = {};
    S.data.species.forEach(function (sp) {
      fams[sp.family] = (fams[sp.family] || 0) + 1;
    });
    Object.keys(fams)
      .sort()
      .forEach(function (fam) {
        var o = document.createElement("option");
        o.value = fam;
        o.textContent = fam + " (" + fams[fam] + ")";
        $("birds-family").appendChild(o);
      });

    Object.keys(S.data.locations)
      .sort(function (a, b) {
        return S.data.locations[a].display.localeCompare(S.data.locations[b].display);
      })
      .forEach(function (key) {
        var o = document.createElement("option");
        o.value = key;
        o.textContent = S.data.locations[key].display;
        $("birds-location").appendChild(o);
      });
  }

  function wire() {
    ["birds-search", "birds-family", "birds-location", "birds-sort"].forEach(function (id) {
      $(id).addEventListener("input", apply);
      $(id).addEventListener("change", apply);
    });
    $("birds-view-gallery").addEventListener("click", function () {
      setView("gallery");
    });
    $("birds-view-map").addEventListener("click", function () {
      setView("map");
    });

    var box = $("birds-lightbox");
    box.querySelector(".lb-close").addEventListener("click", closeLightbox);
    box.querySelector(".lb-prev").addEventListener("click", function (e) {
      e.stopPropagation();
      step(-1);
    });
    box.querySelector(".lb-next").addEventListener("click", function (e) {
      e.stopPropagation();
      step(1);
    });
    box.addEventListener("click", function (e) {
      if (e.target === box) closeLightbox();
    });
    document.addEventListener("keydown", function (e) {
      if (!box.classList.contains("open")) return;
      if (e.key === "Escape") closeLightbox();
      if (e.key === "ArrowLeft") step(-1);
      if (e.key === "ArrowRight") step(1);
    });
  }

  fetch(BASE + "/data.json")
    .then(function (r) {
      if (!r.ok) throw new Error("data.json " + r.status);
      return r.json();
    })
    .then(function (d) {
      S.data = d;
      fillSelects();
      wire();
      apply();
    })
    .catch(function (err) {
      console.error(err);
      $("birds-stats").textContent = "Could not load bird data.";
    });
})();
